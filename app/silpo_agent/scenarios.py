def watchlist_check(prefs):
    """Перевірка, чи повернулись у продаж товари зі списку відстеження."""
    items = ", ".join(prefs.data["watchlist"]) or "(список порожній)"
    return (
        "Перевір наявність товарів з мого списку відстеження: "
        f"{items}. Для кожного скажи: чи є в наявності зараз, ціна, чи є "
        "акція. Якщо товар повернувся в продаж — винеси його на початок "
        "відповіді з позначкою «ЗНОВУ В ПРОДАЖУ». Нічого не додавай у кошик."
    )


